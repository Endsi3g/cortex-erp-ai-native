// Regenerates src/desk/frappe-accent-overrides.css.
// Frappe UI ships a blue accent (semantic variables such as --surface-blue-3). Cortex has one
// accent, its green: every blue variable is re-pointed at the Cortex ramp, step for step.
// Run: node scripts/generate-accent-overrides.mjs
import { writeFileSync } from 'node:fs'
import { generateCSSVariables } from '../node_modules/frappe-ui/tailwind/colorPalette.js'
import palette from '../node_modules/frappe-ui/tailwind/colors.json' with { type: 'json' }

export const CORTEX_RAMP = {
  50: '#E8F7EE', 100: '#C8EDD6', 200: '#A3E3BE', 300: '#5CD094', 400: '#14B86A',
  500: '#087A43', 600: '#066336', 700: '#044C29', 800: '#05361F', 900: '#08120D'
}

const light = generateCSSVariables()[':root']
const stepByHex = Object.fromEntries(Object.entries(palette.lightMode.blue).map(([step, hex]) => [hex.toUpperCase(), step]))
const lines = []
for (const [name, value] of Object.entries(light)) {
  if (!name.includes('blue')) continue
  const step = stepByHex[String(value).toUpperCase()]
  if (step && CORTEX_RAMP[step]) lines.push(`  ${name}: ${CORTEX_RAMP[step]};`)
}
const css = `/* Generated by scripts/generate-accent-overrides.mjs — do not edit by hand. */\n.cortex-root.cortex-root {\n${lines.join('\n')}\n}\n`
writeFileSync(new URL('../src/desk/frappe-accent-overrides.css', import.meta.url), css)
console.log(`${lines.length} blue variables re-pointed at the Cortex green ramp`)
